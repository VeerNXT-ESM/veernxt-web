/**
 * Resolves a book title, slug, or state name to its composited cover image.
 * Ensures General GS books strictly get the General GS cover, while State-specific
 * books get the appropriate state cover.
 */
export function getBookCoverUrl(slugOrTitle, explicitRegion) {
  if (!slugOrTitle && !explicitRegion) return null;

  const raw = String(slugOrTitle || '').trim().toLowerCase();
  const normalized = raw.replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

  // 1. Direct key match in BOOK_COVERS_MAP
  if (BOOK_COVERS_MAP[normalized]) return BOOK_COVERS_MAP[normalized];

  // 2. Strict check for All-India General GS & GK books
  // These should ALWAYS return the General GS cover, NEVER a state cover.
  const isGeneralGS =
    normalized === 'gs-gk' ||
    normalized === 'gk-gs' ||
    normalized === 'gs-gk-complete-guide' ||
    normalized === 'general-knowledge' ||
    normalized === 'general-studies' ||
    normalized === 'ssc-complete-gk' ||
    normalized === 'gen-awareness' ||
    raw === 'gs & gk' ||
    raw === 'gs and gk' ||
    raw === 'general knowledge' ||
    raw === 'general awareness' ||
    raw === 'ssc complete gk' ||
    raw === 'gs & gk guide book';

  if (isGeneralGS) {
    return BOOK_COVERS_MAP['gs-gk-complete-guide'];
  }

  // 3. Specific subjects
  if (normalized.includes('mathematics') || normalized.includes('quant')) {
    return BOOK_COVERS_MAP['mathematics'];
  }
  if (normalized.includes('reasoning')) {
    return BOOK_COVERS_MAP['reasoning'];
  }
  if (normalized.includes('english')) {
    return BOOK_COVERS_MAP['english'];
  }
  if (normalized.includes('hindi')) {
    return BOOK_COVERS_MAP['hindi'];
  }
  if (normalized.includes('computer')) {
    return BOOK_COVERS_MAP['computer-science'];
  }

  // 4. Check if the book title specifically targets a state
  for (const [stateKey, url] of Object.entries(STATE_COVERS_MAP)) {
    if (normalized.includes(stateKey) || normalized.startsWith(stateKey)) {
      return url;
    }
  }

  // 5. If explicitRegion provided (e.g. state exam context for a state-specific book)
  if (explicitRegion) {
    const normReg = String(explicitRegion).trim().toLowerCase().replace(/[^a-z0-9]+/g, '-');
    for (const [stateKey, url] of Object.entries(STATE_COVERS_MAP)) {
      if (normReg.includes(stateKey) || stateKey.includes(normReg)) {
        return url;
      }
    }
  }

  // 6. Generic GS fallback ONLY if it wasn't matched above
  if (normalized.includes('gs') || normalized.includes('gk') || normalized.includes('general-studies')) {
    return BOOK_COVERS_MAP['gs-gk-complete-guide'];
  }

  return null;
}
